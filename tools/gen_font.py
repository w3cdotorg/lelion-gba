ORDRE = " ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789?!:/.-%><',+"


def main():
    octets = []
    for ch in ORDRE:
        rows = GLYPHES[ch]
        assert len(rows) == 7 and all(len(r) == 5 for r in rows), ch
        for r in rows:
            octets.append(int("".join("1" if c == "#" else "0" for c in r) + "000", 2))
        octets.append(0)  # 8th row: spacing
    c = ['#include "font.h"', "", f"const unsigned char font_glyphs[{len(octets)}] = {{"]
    for i in range(0, len(octets), 16):
        c.append("    " + ", ".join(f"0x{b:02X}" for b in octets[i:i + 16]) + ",")
    c.append("};")
    c.append(f'const char font_order[] = "{ORDRE.replace(chr(34), chr(92) + chr(34))}";')
    h = ["#pragma once", "// Generated by tools/gen_font.py — do not edit. 5x7 glyphs in 8x8 cells, MSB = left.",
         f"#define FONT_GLYPH_COUNT {len(ORDRE)}", f"extern const unsigned char font_glyphs[{len(octets)}];",
         "extern const char font_order[];", ""]
    (SORTIE / "font.c").write_text("\n".join(c) + "\n")
    (SORTIE / "font.h").write_text("\n".join(h))
    print(f"font: {len(ORDRE)} glyphs")


if __name__ == "__main__":
    main()
